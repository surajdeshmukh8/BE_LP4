# Import required libraries
import numpy as np
import tensorflow as tf
import gensim
from tensorflow import keras
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Dense, Embedding, Lambda
from tensorflow.keras.preprocessing.text import Tokenizer
from tensorflow.keras.preprocessing.sequence import pad_sequences
print("TensorFlow version:", tf.__version__)
print("Gensim version:", gensim.__version__)
print("Libraries imported successfully!")

# Create an English paragraph of 8 sentences
text = """
Machine learning is an important field of artificial intelligence.
Machine learning helps computers learn from data.
Deep learning uses neural networks to solve complex problems.
Neural networks learn useful patterns from large amounts of data.
Natural language processing helps computers understand human language.
Word embeddings represent words as numerical vectors.
The CBOW model predicts a target word using surrounding context words.
Word2Vec techniques are widely used for learning meaningful word representations.
"""
print(text)

# Convert text to lowercase
text = text.lower()
# Remove punctuation
import string
text = text.translate(str.maketrans('', '', string.punctuation))
print(text)

# Split paragraph into individual sentences
sentences = [
    sentence.strip()
    for sentence in text.split('\n')
    if sentence.strip()
]
print("Total number of sentences:", len(sentences))
for i, sentence in enumerate(sentences, 1):
    print(i, ":", sentence)

# Create tokenizer
tokenizer = Tokenizer()
# Fit tokenizer on the sentences
tokenizer.fit_on_texts(sentences)
# Convert sentences into sequences of word indices
sequences = tokenizer.texts_to_sequences(sentences)
print("Tokenized sentences:")
for sequence in sequences:
  print(sequence)

# Find vocabulary size and number of sentences
word_index = tokenizer.word_index
total_vocab = len(word_index) + 1
total_sentences = len(sentences)
print("Total number of sentences:", total_sentences)
print("Total number of unique words:", len(word_index))
print("Total vocabulary size:", total_vocab)
print("\nWord Index:")
print(word_index)

# Set CBOW window size
window_size = 2
print("Window size:", window_size)
print("Maximum context words:", window_size * 2)

# Generate CBOW context-target pairs
def generate_cbow_data(data, window_size, total_vocab):
    context_data = []
    target_data = []

    for sentence in data:
        sentence_length = len(sentence)
        for idx, word in enumerate(sentence):
            context_words = []
            begin = idx - window_size
            end = idx + window_size + 1

            for i in range(begin, end):
                if 0 <= i < sentence_length and i != idx:
                    context_words.append(sentence[i])
            # Pad context words to fixed length
            context_words = pad_sequences(
                [context_words],
                maxlen=window_size * 2,
                padding='pre'
            )[0]
            context_data.append(context_words)
            target_data.append(word)
    # Convert target values to one-hot encoding
    target_data = keras.utils.to_categorical(
        target_data,
        num_classes=total_vocab
    )
    return np.array(context_data), np.array(target_data)

# Generate training data
X, y = generate_cbow_data(
sequences,
window_size,
total_vocab
)
print("Context data shape:", X.shape)
print("Target data shape:", y.shape)

# Display some context-target examples
reverse_word_index = {
    value: key for key, value in word_index.items()
}
print("Sample CBOW training pairs:\n")
for i in range(min(10, len(X))):
    context_words = [
        reverse_word_index.get(word_id, "<PAD>")
        for word_id in X[i]
        if word_id != 0
    ]
    target_word = reverse_word_index.get(
        np.argmax(y[i]),
        "UNKNOWN"
    )
    print("Context:", context_words)
    print("Target :", target_word)
    print()

# Create CBOW model
embedding_dim = 100
model = Sequential([
# Convert word IDs into embedding vectors
Embedding(
input_dim=total_vocab,
output_dim=embedding_dim
),
# Average the context word embeddings
Lambda(
lambda x: tf.reduce_mean(x, axis=1)
),
# Fully connected layer
Dense(128, activation='relu'),
# Output layer
Dense(total_vocab, activation='softmax')
])
print("CBOW model created successfully!")

# Build the model
model.build(input_shape=(None, window_size * 2))
model.summary()

# Compile CBOW model
model.compile(
loss='categorical_crossentropy',
optimizer='adam',
metrics=['accuracy']
)
print("CBOW model compiled successfully!")

# Train the CBOW model
history = model.fit(
X,
y,
epochs=100,
batch_size=16,
verbose=1
)

# Plot training loss
import matplotlib.pyplot as plt
plt.figure(figsize=(8, 5))
plt.plot(history.history['loss'])
plt.title('CBOW Training Loss')
plt.xlabel('Epoch')
plt.ylabel('Loss')
plt.grid()
plt.show()

# Plot training accuracy
plt.figure(figsize=(8, 5))
plt.plot(history.history['accuracy'])
plt.title('CBOW Training Accuracy')
plt.xlabel('Epoch')
plt.ylabel('Accuracy')
plt.grid()
plt.show()

# Extract word embedding weights
weights = model.get_weights()[0]
print("Embedding matrix shape:", weights.shape)
print("Embedding dimension:", embedding_dim)

# Create Word2Vec-compatible vector file
vector_file = "/content/vectors.txt"
with open(vector_file, "w") as f:
    # Header: vocabulary size and vector dimensions
    f.write(f"{total_vocab} {embedding_dim}\n")
    # Write embedding for index 0 (padding/unknown token)
    vector_for_zero = weights[0]
    vector_string_for_zero = " ".join(map(str, vector_for_zero))
    f.write(f"<PAD> {vector_string_for_zero}\n")
    for word, index in word_index.items():
        vector = weights[index]
        vector_string = " ".join(map(str, vector))
        f.write(f"{word} {vector_string}\n")

print("Vector file created successfully!")
print("File location:", vector_file)

# Load the trained word vectors
from gensim.models import KeyedVectors
cbow_output = KeyedVectors.load_word2vec_format(
vector_file,
binary=False
)
print("Word vectors loaded successfully!")
print("Number of vectors:", len(cbow_output))
print("Vector size:", cbow_output.vector_size)

# Find similar words
word = "learning"
similar_words = cbow_output.most_similar(
    positive=[word],
    topn=5
)
print(f"Words most similar to '{word}':")
for w, score in similar_words:
    print(f"{w}: {score:.4f}")

# Test another word
word = "model"
similar_words = cbow_output.most_similar(
    positive=[word],
    topn=5
)
print(f"Words most similar to '{word}':")
for w, score in similar_words:
    print(f"{w}: {score:.4f}")

# Display the vector of a word
word = "learning"
vector = cbow_output[word]
print("Word:", word)
print("Vector dimension:", len(vector))
print("\nFirst 10 values of vector:")
print(vector[:10])

# Display final CBOW results
print("=" * 50)
print("CBOW MODEL - FINAL RESULTS")
print("=" * 50)
print("Number of sentences :", total_sentences)
print("Vocabulary size      :", total_vocab)
print("Window size          :", window_size)
print("Embedding dimension  :", embedding_dim)
print("Training samples     :", len(X))
print("\nSelected word :", "learning")
print("\nSimilar words:")
for word, score in cbow_output.most_similar(
    positive=["learning"],
    topn=5
):
    print(f"{word:15s} : {score:.4f}")
