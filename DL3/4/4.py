# Import required libraries
import pandas as pd
import numpy as np
import tensorflow as tf
import matplotlib.pyplot as plt
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import MinMaxScaler
from sklearn.metrics import accuracy_score
from tensorflow.keras import Model, Sequential
from tensorflow.keras.layers import Dense, Dropout
from tensorflow.keras.optimizers import Adam
from tensorflow.keras.losses import MeanSquaredLogarithmicError
print("Libraries imported successfully!")
print("TensorFlow Version:", tf.__version__)

# ECG dataset URL
url = "http://storage.googleapis.com/download.tensorflow.org/data/ecg.csv"
# Load dataset
df = pd.read_csv(url)
print("Dataset loaded successfully!")
print("Dataset shape:", df.shape)

# Display first five rows
df.head()

# Display dataset information
print("Number of rows:", df.shape[0])
print("Number of columns:", df.shape[1])
print("\nColumn names:")
print(df.columns)
print("\nMissing values:")
print(df.isnull().sum().sum())

# Separate features and target
features = df.iloc[:, :-1]
target = df.iloc[:, -1]
print("Features shape:", features.shape)
print("Target shape:", target.shape)
print("\nTarget classes:")
print(target.value_counts())

# Split dataset into training and testing data
x_train, x_test, y_train, y_test = train_test_split(
features,
target,
test_size=0.2,
stratify=target,
random_state=42
)
print("Training data shape:", x_train.shape)
print("Testing data shape:", x_test.shape)
print("Training target shape:", y_train.shape)
print("Testing target shape:", y_test.shape)

# Select only normal ECG samples for training
# Target class 1 represents normal ECG
x_train = x_train[y_train == 1]
print("Normal ECG training data shape:", x_train.shape)

# Scale the ECG data between 0 and 1
scaler = MinMaxScaler()
x_train_scaled = scaler.fit_transform(x_train)
x_test_scaled = scaler.transform(x_test)
print("Training scaled data shape:", x_train_scaled.shape)
print("Testing scaled data shape:", x_test_scaled.shape)
print("Minimum value:", x_train_scaled.min())
print("Maximum value:", x_train_scaled.max())

# Create AutoEncoder using Keras Model class
class AutoEncoder(Model):
    def __init__(self, output_units):
        super().__init__()
        # Encoder - 4 layers
        self.encoder = Sequential([
            Dense(128, activation='relu'),
            Dense(64, activation='relu'),
            Dense(32, activation='relu'),
            Dense(16, activation='relu')
        ])
        # Decoder - 4 layers
        self.decoder = Sequential([
            Dense(32, activation='relu'),
            Dense(64, activation='relu'),
            Dense(128, activation='relu'),
            Dense(output_units, activation='sigmoid')
        ])
    def call(self, inputs):
        encoded = self.encoder(inputs)
        decoded = self.decoder(encoded)
        return decoded
print("AutoEncoder class created successfully!")

# Create Autoencoder model
model = AutoEncoder(output_units=x_train_scaled.shape[1])
print("Autoencoder model created successfully!")

# Build the model
model.build(input_shape=(None, x_train_scaled.shape[1]))
model.summary()

# Compile the Autoencoder
model.compile(
optimizer=Adam(),
loss=MeanSquaredLogarithmicError(),
metrics=['mse']
)
print("Model compiled successfully!")

# Train the Autoencoder
history = model.fit(
x_train_scaled,
x_train_scaled,
epochs=20,
batch_size=512,
validation_data=(x_test_scaled, x_test_scaled),
verbose=1
)

# Plot training and validation loss
plt.figure(figsize=(8, 5))
plt.plot(history.history['loss'], label='Training Loss')
plt.plot(history.history['val_loss'], label='Validation Loss')
plt.title('Training and Validation Loss')
plt.xlabel('Epoch')
plt.ylabel('Mean Squared Logarithmic Error')
plt.legend()
plt.grid()
plt.show()

# Plot training and validation MSE
plt.figure(figsize=(8, 5))
plt.plot(history.history['mse'], label='Training MSE')
plt.plot(history.history['val_mse'], label='Validation MSE')
plt.title('Training and Validation MSE')
plt.xlabel('Epoch')
plt.ylabel('MSE')
plt.legend()
plt.grid()
plt.show()

# Reconstruct training ECG signals
train_reconstructions = model.predict(x_train_scaled, verbose=0)
print("Reconstruction shape:", train_reconstructions.shape)

# Calculate reconstruction errors for training data
reconstruction_errors = tf.keras.losses.msle(
x_train_scaled,
train_reconstructions
)
print("Reconstruction errors calculated successfully!")
print("Mean reconstruction error:",
np.mean(reconstruction_errors.numpy()))
print("Maximum reconstruction error:",
np.max(reconstruction_errors.numpy()))

# Calculate anomaly threshold
threshold = (
np.mean(reconstruction_errors.numpy())
+ np.std(reconstruction_errors.numpy())
)
print("Anomaly Threshold:", threshold)

# Reconstruct test ECG signals
test_reconstructions = model.predict(
x_test_scaled,
verbose=0
)
# Calculate reconstruction errors for test data
test_reconstruction_errors = tf.keras.losses.msle(
x_test_scaled,
test_reconstructions
)
print("Test reconstruction errors calculated!")

# Predict anomalies using threshold
predicted_labels = (
test_reconstruction_errors.numpy() > threshold
).astype(int)
print("Predictions generated successfully!")
print("First 20 predictions:")
print(predicted_labels[:20])

# Calculate accuracy score
accuracy = accuracy_score(
y_test,
predicted_labels
)
print("Accuracy Score:", accuracy)
print("Accuracy Percentage:", accuracy * 100)

from sklearn.metrics import confusion_matrix, classification_report
# Confusion Matrix
cm = confusion_matrix(y_test, predicted_labels)
print("Confusion Matrix:")
print(cm)
print("\nClassification Report:")
print(
classification_report(
y_test,
predicted_labels,
target_names=['Anomaly', 'Normal']
)
)

# Plot reconstruction errors
plt.figure(figsize=(10, 5))
plt.hist(
reconstruction_errors.numpy(),
bins=50,
label='Normal Training Errors'
)
plt.axvline(
threshold,
linestyle='--',
label='Anomaly Threshold'
)
plt.title('Reconstruction Error Distribution')
plt.xlabel('Reconstruction Error')
plt.ylabel('Number of Samples')
plt.legend()
plt.grid()
plt.show()

# Display final results
print("=" * 50)
print("ECG ANOMALY DETECTION - FINAL RESULTS")
print("=" * 50)
print(f"Training Samples : {len(x_train_scaled)}")
print(f"Testing Samples : {len(x_test_scaled)}")
print(f"Anomaly Threshold : {threshold:.6f}")
print(f"Accuracy Score : {accuracy:.4f}")
print(f"Accuracy Percentage : {accuracy * 100:.2f}%")
print("=" * 50)

# Count predicted normal and anomalous ECG signals
normal_count = np.sum(predicted_labels == 0)
anomaly_count = np.sum(predicted_labels == 1)
print("Predicted Normal ECGs :", normal_count)
print("Predicted Anomalous ECGs :", anomaly_count)