import tensorflow as tf
from tensorflow import keras
from tensorflow.keras import layers
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
print("TensorFlow Version:", tf.__version__)
print("Libraries imported successfully!")

# Load CIFAR-10 dataset
(X_train, y_train), (X_test, y_test) = keras.datasets.cifar10.load_data()
print("Training images shape:", X_train.shape)
print("Training labels shape:", y_train.shape)
print("Testing images shape:", X_test.shape)
print("Testing labels shape:", y_test.shape)

# Define class names
CATEGORIES = [
'airplane',
'automobile',
'bird',
'cat',
'deer',
'dog',
'frog',
'horse',
'ship',
'truck'
]
print("Number of categories:", len(CATEGORIES))
print("Categories:", CATEGORIES)

# Display sample images
plt.figure(figsize=(10, 6))
for i in range(12):
  plt.subplot(3, 4, i + 1)
  plt.imshow(X_train[i])
  plt.title(CATEGORIES[y_train[i][0]])
  plt.axis('off')
plt.tight_layout()
plt.show()

# Normalize pixel values from 0-255 to 0-1
X_train = X_train.astype('float32') / 255.0
X_test = X_test.astype('float32') / 255.0
print("Minimum pixel value:", X_train.min())
print("Maximum pixel value:", X_train.max())

# Convert class labels into categorical format
y_train = keras.utils.to_categorical(y_train, 10)
y_test = keras.utils.to_categorical(y_test, 10)
print("Training labels shape:", y_train.shape)
print("Testing labels shape:", y_test.shape)

# Display final dataset shapes
print("X_train:", X_train.shape)
print("y_train:", y_train.shape)
print("X_test:", X_test.shape)
print("y_test:", y_test.shape)
X_train: (50000, 32, 32, 3)
y_train: (50000, 10)
X_test: (10000, 32, 32, 3)
y_test: (10000, 10)

# Define CNN model
model = keras.Sequential([
keras.Input(shape=(32, 32, 3)),
# First convolution layer
layers.Conv2D(32, (3, 3), activation='relu'),
# First pooling layer
layers.MaxPooling2D((2, 2)),
# Second convolution layer
layers.Conv2D(64, (3, 3), activation='relu'),
# Second pooling layer
layers.MaxPooling2D((2, 2)),
# Convert feature maps into one-dimensional vector
layers.Flatten(),
# Fully connected layer
layers.Dense(128, activation='relu'),
# Output layer - 10 classes
layers.Dense(10, activation='softmax')
])
print("CNN model created successfully!")

# Display model architecture
model.summary()

# Compile the CNN model
model.compile(
optimizer='adam',
loss='categorical_crossentropy',
metrics=['accuracy']
)
print("Model compiled successfully!")

# Train the CNN model
history = model.fit(
X_train,
y_train,
epochs=10,
batch_size=64,
validation_split=0.1,
verbose=1
)

# Evaluate the model on test data
test_loss, test_accuracy = model.evaluate(X_test, y_test, verbose=1)
print("Test Loss:", test_loss)
print("Test Accuracy:", test_accuracy)
print("Test Accuracy Percentage:", test_accuracy * 100)

# Plot training and validation accuracy
plt.figure(figsize=(8, 5))
plt.plot(history.history['accuracy'], label='Training Accuracy')
plt.plot(history.history['val_accuracy'], label='Validation Accuracy')
plt.title('Training and Validation Accuracy')
plt.xlabel('Epoch')
plt.ylabel('Accuracy')
plt.legend()
plt.grid()
plt.show()

# Plot training and validation loss
plt.figure(figsize=(8, 5))
plt.plot(history.history['loss'], label='Training Loss')
plt.plot(history.history['val_loss'], label='Validation Loss')
plt.title('Training and Validation Loss')
plt.xlabel('Epoch')
plt.ylabel('Loss')
plt.legend()
plt.grid()
plt.show()

# Make predictions on test images
predictions = model.predict(X_test)
print("Predictions generated successfully!")
print("Prediction shape:", predictions.shape)

# Display predicted and actual classes
plt.figure(figsize=(10, 8))

for i in range(12):
    plt.subplot(3, 4, i + 1)
    plt.imshow(X_test[i])

    predicted_class = np.argmax(predictions[i])
    actual_class = np.argmax(y_test[i])
    plt.title(
        f"Pred: {CATEGORIES[predicted_class]}\n"
        f"Actual: {CATEGORIES[actual_class]}"
    )
    plt.axis('off')
plt.tight_layout()
plt.show()

# Calculate correct predictions
predicted_labels = np.argmax(predictions, axis=1)
actual_labels = np.argmax(y_test, axis=1)
correct_predictions = np.sum(predicted_labels == actual_labels)
total_predictions = len(actual_labels)
print("Correct Predictions:", correct_predictions)
print("Total Predictions:", total_predictions)
print("Accuracy:", correct_predictions / total_predictions * 100, "%")

# Test a single image
index = 25
image = X_test[index]
actual = np.argmax(y_test[index])
prediction = model.predict(np.expand_dims(image, axis=0), verbose=0)
predicted = np.argmax(prediction)
plt.imshow(image)
plt.title(
f"Predicted: {CATEGORIES[predicted]}\n"
f"Actual: {CATEGORIES[actual]}"
)
plt.axis('off')
plt.show()
print("Predicted Class:", CATEGORIES[predicted])
print("Actual Class:", CATEGORIES[actual])