import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import tensorflow as tf
from tensorflow.keras import models, layers, optimizers, datasets, backend
from sklearn.preprocessing import LabelBinarizer
from sklearn.metrics import classification_report

(x_train, y_train), (x_test, y_test) = datasets.mnist.load_data()
print("Training data shape:", x_train.shape)
print("Testing data shape:", x_test.shape)

plt.imshow(x_train[0], cmap='gray')
plt.title("Sample MNIST Image")
plt.axis('off')
plt.show()
print("Label:", y_train[0])

x_train = x_train.astype("float32") / 255.0
x_test = x_test.astype("float32") / 255.0

x_train = x_train.reshape(x_train.shape[0], 784)
x_test = x_test.reshape(x_test.shape[0], 784)
print("Training shape after flattening:", x_train.shape)
print("Testing shape after flattening:", x_test.shape)

lb = LabelBinarizer()
y_train = lb.fit_transform(y_train)
y_test = lb.transform(y_test)
print("Label shape:", y_train.shape)

model = models.Sequential([
layers.Input(shape=(784,)),
layers.Dense(128, activation='sigmoid'),
layers.Dense(64, activation='sigmoid'),
layers.Dense(10, activation='softmax')
])

model.summary()

optimizer = optimizers.SGD(learning_rate=0.01)
model.compile(
optimizer=optimizer,
loss='categorical_crossentropy',
metrics=['accuracy']
)

model.summary()

history = model.fit(
x_train,
y_train,
epochs=10,
batch_size=128,
validation_split=0.1
)

test_loss, test_accuracy = model.evaluate(x_test, y_test)
print("Test Loss:", test_loss)
print("Test Accuracy:", test_accuracy)

predictions = model.predict(x_test)
predicted_classes = np.argmax(predictions, axis=1)
actual_classes = np.argmax(y_test, axis=1)
print("Predicted:", predicted_classes[:10])
print("Actual: ", actual_classes[:10])

print(classification_report(
actual_classes,
predicted_classes
))

plt.figure(figsize=(8, 5))
plt.plot(history.history['accuracy'], label='Training Accuracy')
plt.plot(history.history['val_accuracy'], label='Validation Accuracy')
plt.title('Training and Validation Accuracy')
plt.xlabel('Epoch')
plt.ylabel('Accuracy')
plt.legend()
plt.show()

plt.figure(figsize=(8, 5))
plt.plot(history.history['loss'], label='Training Loss')
plt.plot(history.history['val_loss'], label='Validation Loss')
plt.title('Training and Validation Loss')
plt.xlabel('Epoch')
plt.ylabel('Loss')
plt.legend()
plt.show()

plt.figure(figsize=(10, 5))
for i in range(10):
  plt.subplot(2, 5, i + 1)
  image = x_test[i].reshape(28, 28)
  plt.imshow(image, cmap='gray')
  plt.title(f"Pred: {predicted_classes[i]}")
  plt.axis('off')
plt.tight_layout()
plt.show()

